import { fileURLToPath } from 'node:url';
import { createDatabase, migrateToLatest } from '@fd/chassis-postgres';
import { startPostgresContainer, type StartedPostgres } from '@fd/chassis-testing';
import { Cli, TypeScriptSerializer } from 'kysely-codegen';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { accountingMigrationSources } from './accounting-migration-sources.config.ts';

const generatedTypesFile = fileURLToPath(new URL('./generated/database.ts', import.meta.url));

let postgres: StartedPostgres;
let appliedMigrations: readonly string[];

beforeAll(async () => {
  postgres = await startPostgresContainer();
  const database = createDatabase({
    connectionString: postgres.connectionUri,
    maximumConnectionCount: 1,
    onConnectionError: () => undefined,
  });
  appliedMigrations = await migrateToLatest(database, accountingMigrationSources);
  await database.destroy();
});

afterAll(async () => {
  await postgres.stop();
});

describe('accountingMigrationSources', () => {
  it('applies the outbox, inbox and accounting migrations', () => {
    expect(appliedMigrations).toEqual([
      'accounting/0001-create-payments-table',
      'accounting/0002-add-payment-restaurant-and-delivery-fee',
      'inbox/0001-create-inbox-table',
      'outbox/0001-create-outbox-table',
    ]);
  });

  it('matches the committed database types (UPDATE_GOLDEN=1 rewrites them)', async () => {
    const generation = new Cli().generate({
      url: postgres.connectionUri,
      camelCase: true,
      typeMapping: { int8: 'bigint' },
      excludePattern: '{inbox,outbox,kysely_*}',
      serializer: new TypeScriptSerializer({ skipAutogeneratedFileComment: true }),
      outFile: generatedTypesFile,
      verify: process.env['UPDATE_GOLDEN'] !== '1',
      logLevel: 'error',
    });

    await expect(generation).resolves.toContain('export interface DB');
  });
});
